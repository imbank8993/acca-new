/** Generate application icons and link previews from the current sidebar logos. */
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');

async function writeIfChanged(file, data) {
    const next = Buffer.isBuffer(data) ? data : Buffer.from(data);
    try { if ((await fs.readFile(file)).equals(next)) return; }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
    await fs.writeFile(file, next);
}

async function main() {
    const root = path.resolve(__dirname, '..');
    const publicRoot = path.join(root, 'public');
    const config = JSON.parse(await fs.readFile(path.join(root, 'branding.config.json'), 'utf8'));
    const symbol = await fs.readFile(path.join(publicRoot, config.symbol));
    const wordmark = await fs.readFile(path.join(publicRoot, config.wordmark));
    const darkWordmark = await fs.readFile(path.join(publicRoot, config.wordmarkDark));
    const version = crypto.createHash('sha256').update(symbol).update(wordmark).update(darkWordmark).digest('hex').slice(0, 12);
    const out = path.join(publicRoot, 'branding');
    await fs.mkdir(out, { recursive: true });
    const brand = {
        name: config.name,
        logo: `/${config.symbol}?v=${version}`,
        wordmark: `/${config.wordmark}?v=${version}`,
        wordmarkDark: `/${config.wordmarkDark}?v=${version}`,
        icon: `/branding/acca-${version}-192.png`,
        appleIcon: `/branding/acca-${version}-180.png`,
        appIcon: `/branding/acca-${version}-512.png`,
        shareImage: `/branding/acca-${version}-share.png`,
    };
    for (const [key, size] of [['icon', 192], ['appleIcon', 180], ['appIcon', 512]]) {
        const mark = await sharp(symbol).resize({ width: Math.round(size * 0.70), height: Math.round(size * 0.70), fit: 'inside' }).png().toBuffer();
        await sharp({ create: { width: size, height: size, channels: 4, background: '#ffffff' } })
            .composite([{ input: mark, gravity: 'centre' }]).png().toFile(path.join(publicRoot, brand[key]));
    }
    const socialWordmark = await sharp(wordmark).resize({ width: 960, height: 230, fit: 'inside' }).png().toBuffer();
    await sharp({ create: { width: 1200, height: 630, channels: 4, background: '#ffffff' } })
        .composite([{ input: socialWordmark, gravity: 'centre' }]).png().toFile(path.join(publicRoot, brand.shareImage));

    // Legacy URLs are still used by PDF generators and previously shared links.
    await writeIfChanged(path.join(publicRoot, 'logo-icon.png'), symbol);
    await writeIfChanged(path.join(publicRoot, 'logo_final.png'), symbol);
    await sharp(symbol).webp({ lossless: true }).toFile(path.join(publicRoot, 'logo-sidebar-kecil.webp'));
    const size = await sharp(symbol).metadata();
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ${size.width} ${size.height}"><image width="${size.width}" height="${size.height}" xlink:href="data:image/png;base64,${symbol.toString('base64')}"/></svg>\n`;
    for (const file of ['public/icon.svg', 'public/Logo.svg', 'app/icon.svg']) await writeIfChanged(path.join(root, file), svg);

    const generated = '// Generated by scripts/sync-branding.cjs. Edit branding.config.json and its source images.\n';
    await writeIfChanged(path.join(root, 'lib/branding.ts'), generated + `export const APP_BRAND = ${JSON.stringify(brand, null, 2)} as const;\n`);
    await writeIfChanged(path.join(root, 'lib/branding-logo.ts'), generated + `export const APP_LOGO_DATA_URI = 'data:image/png;base64,${symbol.toString('base64')}';\n`);
    const manifestPath = path.join(publicRoot, 'manifest.json');
    const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'));
    manifest.icons = [192, 512].map(size => ({ src: size === 192 ? brand.icon : brand.appIcon, sizes: `${size}x${size}`, type: 'image/png', purpose: 'any' }));
    await writeIfChanged(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
    console.log(`Branding ${config.name} synchronized (${version}).`);
}

main().catch(error => { console.error(error); process.exitCode = 1; });
